# Number Conversion
x = 10.75
print(int(x))

x = 10
print(float(x))

x = complex(5)
print(x)
x = complex(5, 3)
print(x)


x = 10.5678
print(round(x))
print(round(x, 2))
print(round(x, 3))
print(round(x, 4))
print(round(x, 5))



# abs() — Absolute Value
